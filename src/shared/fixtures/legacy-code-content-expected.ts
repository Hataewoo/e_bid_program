/** code → 기대 gap 개수 (= 매칭 횟수 − 1) */
export function expectedGapCount(code: string, side: 'low' | 'high' = 'low'): number | undefined {
  const map = side === 'low' ? LEGACY_MASTER_00_CODE_CONTENT : LEGACY_MASTER_00_STEP3_CODE_CONTENT;
  const s = map[code];
  if (!s) return undefined;
  return s.split(',').length;
}

/** 13코드 gap 총합 */
export function totalExpectedGapCount(side: 'low' | 'high' = 'low'): number {
  const order = side === 'low' ? LEGACY_STEP2_CODE_ORDER : LEGACY_STEP3_CODE_ORDER;
  const map = side === 'low' ? LEGACY_MASTER_00_CODE_CONTENT : LEGACY_MASTER_00_STEP3_CODE_CONTENT;
  return order.reduce((sum, code) => sum + (map[code]?.split(',').length ?? 0), 0);
}
